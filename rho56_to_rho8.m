function rho8 = rho56_to_rho8(rho56, mode, block_id)
% rho56_to_rho8
% ------------------------------------------------------------
% 将 rho56(56×56×N) 提取/压缩回 rho8(8×8×N)
%
% 支持两种模式：
%
% 1) mode = 'first'
%    只提取左上角第一个 8×8 block
%
% 2) mode = 'block'
%    提取指定 block_id 的 8×8 block
%
% 3) mode = 'sum'
%    对所有 7 个 block 求和
%
% ------------------------------------------------------------
%
% 输入：
%
%   rho56    : 56×56×N
%
%   mode     :
%       'first'
%       'block'
%       'sum'
%
%   block_id :
%       当 mode='block' 时需要
%       范围 1~7
%
% ------------------------------------------------------------
%
% 输出：
%
%   rho8 : 8×8×N
%
% ------------------------------------------------------------

    if nargin < 2
        mode = 'first';
    end

    s = size(rho56);

    if numel(s) ~= 3
        error('输入必须为 56×56×N');
    end

    if s(1) ~= 56 || s(2) ~= 56
        error('输入矩阵必须为 56×56×N');
    end

    N = s(3);

    rho8 = zeros(8,8,N);

    switch lower(mode)

        % =====================================================
        % 只取第一个 block
        % =====================================================
        case 'first'

            rho8 = rho56(1:8,1:8,:);

        % =====================================================
        % 提取指定 block
        % =====================================================
        case 'block'

            if nargin < 3
                error('mode=block 时必须提供 block_id');
            end

            if block_id < 1 || block_id > 7
                error('block_id 必须在 1~7');
            end

            idx = (block_id-1)*8 + (1:8);

            rho8 = rho56(idx,idx,:);

        % =====================================================
        % 所有 block 求和
        % =====================================================
        case 'sum'

            for b = 1:7

                idx = (b-1)*8 + (1:8);

                rho8 = rho8 + rho56(idx,idx,:);

            end

        otherwise

            error('未知 mode');

    end

end