function rho56 = rho8_to_rho56(rho8)
% rho8_to_rho56
% ------------------------------------------------------------
% 将 rho(8×8×N) 扩展为 rho56(56×56×N)
%
% 规则：
%   56 = 7 × 8
%
% 即：
%   把原来的 8×8 内态密度矩阵，
%   放到 56×56 大矩阵的左上 block，
%   其它位置补零。
%
% 常用于：
%   多动量态 / 多 block 哈密顿量仿真中，
%   将单 internal-state 密度矩阵嵌入总 Hilbert 空间。
%
% 输入：
%   rho8   : 8×8×N
%
% 输出：
%   rho56  : 56×56×N
%
% ------------------------------------------------------------

    % -------- 检查输入 --------
    s = size(rho8);

    if numel(s) ~= 3
        error('输入必须是 8×8×N');
    end

    if s(1) ~= 8 || s(2) ~= 8
        error('输入前两维必须为 8×8');
    end

    N = s(3);

    % -------- 初始化 --------
    rho56 = zeros(56,56,N);

    % -------- 填充 --------
    for k = 1:N
        rho56(1:8,1:8,k) = rho8(:,:,k);
    end

end